import assert from "node:assert/strict";
import { after, test } from "node:test";
import { randomUUID } from "node:crypto";
import { localConfig } from "../../src/platform/config";
import { closeDatabase } from "../../src/platform/database";
import { httpAcceptance } from "../helpers/acceptance-http";
import { projectInput } from "../helpers/projects";
import { raidInput, raidAction } from "../helpers/project-raid";
import { crmBase } from "../helpers/crm";
if(localConfig().database_name!=="ppo_synthetic_test") throw Error("Only disposable ppo_synthetic_test");
after(closeDatabase);
const h=httpAcceptance(localConfig().origin);
test("PJ04-HTTP01 compiled project-to-RAID-to-Activity closure and original receipt recovery",async()=>{
  const project=projectInput(), item=raidInput(), action=raidAction(project.id);
  assert.equal((await h.call("coordinator","projects",project)).status,201);
  assert.equal((await h.call("coordinator","activities",action)).status,201);
  item.action_ids=[action.id]; const route=`projects/${project.id}/raid`;
  const saved=await h.call("coordinator",route,item); assert.equal(saved.status,201,JSON.stringify(saved.body));
  const replay=await h.call("coordinator",route,item); assert.equal(replay.status,200); assert.deepEqual(replay.body,saved.body);
  const detail=await h.call("coordinator",`${route}?id=${item.id}`);
  assert.equal(detail.status,200); assert.equal(detail.body.current.actions[0].id,action.id);
  const closing={...item,...crmBase(),expected_version:1,state:"Closed",outcome:"SYN agreed follow-up complete"};
  const refused=await h.call("coordinator",route,closing); assert.equal(refused.status,409); assert.equal(refused.body.code,"OpenActions");
  assert.equal((await h.call("coordinator",`activities/${action.id}/complete`,{...crmBase(),expected_version:1,outcome:"SYN confirmed"})).status,200);
  assert.equal((await h.call("coordinator",route,closing)).status,201);
  const closed=await h.call("coordinator",`${route}?id=${item.id}`);
  assert.equal(closed.body.current.state,"Closed"); assert.equal(closed.body.history.length,2);
  const original=await h.call("coordinator",`operations/${item.operation_id}`); assert.equal(original.status,200); assert.deepEqual(original.body,saved.body);
});
test("PJ04-HTTP02 unknown fields, cross-company IDs, stale writes and invalid cursor are refused",async()=>{
  const project=projectInput(), item=raidInput(); await h.call("coordinator","projects",project);
  const route=`projects/${project.id}/raid`; assert.equal((await h.call("coordinator",route,item)).status,201);
  for (const query of ["",`?id=${item.id}`]) assert.equal((await h.call("second-company",route+query)).status,404);
  assert.equal((await h.call("second-company",route,{...item,...crmBase()})).status,404);
  assert.equal((await h.call("coordinator",route,{...item,...crmBase(),approved:true})).status,422);
  assert.equal((await h.call("coordinator",route,{...item,...crmBase(),expected_version:9})).status,409);
  assert.equal((await h.call("coordinator",route+"?cursor=forged")).status,422);
  assert.equal((await h.call("coordinator",route+`?id=${randomUUID()}`)).status,404);
});
