import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {resolve,extname} from 'node:path';
import {chromium} from 'playwright';
const root=process.cwd(),out=resolve(root,'verification-evidence/estimating-design/wizard');
await mkdir(out,{recursive:true});
const allowed=new Set(['/docs/blueprints/estimating-wizard-mockup.html','/docs/blueprints/estimating-wizard-model.mjs','/public/brand/Roboto-variable.woff','/public/brand/powerplants-logo-green-white.png']);
const server=createServer(async(req,res)=>{const url=new URL(req.url,'http://localhost');if(!allowed.has(url.pathname)){res.writeHead(404);res.end();return;}try{const file=resolve(root,'.'+url.pathname);const types={'.html':'text/html','.mjs':'text/javascript','.woff':'font/woff','.png':'image/png'};res.writeHead(200,{'Content-Type':types[extname(file)]});res.end(await readFile(file));}catch{res.writeHead(404);res.end();}});
await new Promise(done=>server.listen(0,'127.0.0.1',done));
const origin=`http://127.0.0.1:${server.address().port}`;
let browser;const observations=[];
try{
 browser=await chromium.launch({headless:true});
 for(const width of [1440,390,320]){
  const page=await browser.newPage({viewport:{width,height:900}});const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/*',route=>route.request().url().startsWith(origin+'/')?route.continue():route.abort());
  await page.goto(origin+'/docs/blueprints/estimating-wizard-mockup.html');
  await page.evaluate(()=>document.fonts.ready);
  const capture=async(name)=>{assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Outer overflow: ${width} ${name}`);await page.screenshot({path:resolve(out,`${width}-${name}.png`),fullPage:true});};
  await capture('requirements');
  await page.getByRole('button',{name:'Review proposed solution',exact:true}).click();
  assert.ok((await page.locator('#solution-totals').innerText()).includes('$2,440.00'));
  await capture('proposal');
  await page.getByRole('button',{name:'Use this draft',exact:true}).click();
  await page.getByLabel('Installation hours',{exact:true}).fill('5.5');
  await page.getByLabel('Reason for adjustment',{exact:true}).fill('Extra access and cable routing time');
  await page.getByRole('button',{name:'Apply labour adjustment',exact:true}).click();
  assert.ok((await page.locator('#estimate-totals').innerText()).includes('$2,620.00'));
  await capture('estimate');
  await page.getByRole('button',{name:'Change requirements',exact:true}).click();
  await page.getByLabel('Sensor positions',{exact:false}).fill('6');
  await page.getByRole('button',{name:'Review proposed solution',exact:true}).click();
  await page.getByRole('button',{name:'Apply reviewed changes',exact:true}).click();
  assert.ok((await page.getByRole('alert').innerText()).includes('Resolve every manual adjustment'));
  await page.getByLabel('Manual adjustment',{exact:true}).selectOption('keep');
  await capture('rerun');
  await page.getByRole('button',{name:'Apply reviewed changes',exact:true}).click();
  assert.ok((await page.locator('#estimate-totals').innerText()).includes('$2,980.00'));
  await page.getByRole('button',{name:'Prepare quotation draft',exact:true}).click();
  const quote=await page.locator('#quote-body').innerText();
  assert.ok(quote.includes('$2,980.00')&&quote.includes('6 demonstration sensors'));
  assert.ok(!quote.includes('Extra access')&&!quote.includes('Internal cost')&&!quote.includes('Unit cost'));
  await capture('quotation');
  await page.getByRole('button',{name:'1 Requirements',exact:true}).click();
  await page.getByLabel('Gateway requirement',{exact:true}).selectOption('unknown');
  await page.getByRole('button',{name:'Review proposed solution',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Apply reviewed changes',exact:true}).isDisabled(),true);
  assert.ok((await page.locator('#missing').innerText()).includes('Incomplete draft'));
  await page.getByRole('button',{name:'Cancel changes',exact:true}).click();
  assert.ok((await page.locator('#estimate-totals').innerText()).includes('$2,980.00'));
  assert.deepEqual(errors,[]);
  observations.push({width,passed:true,flow:'baseline/manual-edit/rerun-choice/quote/unknown/cancel',captures:5});
  await page.close();
 }
 await writeFile(resolve(out,'results.json'),JSON.stringify({source_head:process.env.PPO_SOURCE_HEAD??'local-unspecified',scope:'Standalone synthetic wizard design; no PPO runtime/persistence acceptance',observations},null,2)+'\n');
 console.log(JSON.stringify({status:'passed',observations},null,2));
}finally{if(browser)await browser.close();await new Promise(done=>server.close(done));}
