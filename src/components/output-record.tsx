function ExactIssue({ detail }: { detail: OutputDetail }) {
  const issue = detail.selected_issue;
  if (!issue)
    return (
      <div className="output-empty">
        <ProductIcon name="documents" />
        <h2>
          {detail.availability === "NotProvided"
            ? "Issue not provided"
            : "No issued output"}
        </h2>
        <p>
          {detail.availability === "NotProvided"
            ? "Your permitted source view does not provide an issue. Continue through your native job page."
            : "Preparation and review do not create an issued identity. Review preparation or continue on the native page."}
        </p>
        <ButtonLink href={detail.output.native_href}>
          Open {familyLabel(detail.output.kind).toLowerCase()}
        </ButtonLink>
      </div>
    );
  return (
    <>
      <div
        className={`output-notice ${detail.availability === "ExactUnavailable" ? "output-warning" : ""}`}
      >
        <header>
          <ProductIcon
            name={detail.availability === "Available" ? "documents" : "warning"}
          />
          <h2>
            {detail.availability === "Available"
              ? "Exact issued output"
              : "Exact output unavailable"}
          </h2>
        </header>
        <p>
          {detail.availability === "Available"
            ? "These are the retained files for this selected issue. Each link checks your current authority."
            : "The selected issue is retained, but its exact output cannot be verified. No successor has been substituted and no file has been regenerated."}
        </p>
        <p>
          Issued <OutputTime value={issue.issued_at} /> ·{" "}
          {revisionLabel(issue.revision.revision)} ·{" "}
          {issue.is_current_issue ? "Current issue" : "Earlier issue"}
        </p>
      </div>
      {detail.availability === "Available" && issue.files ? (
        <div className="output-file-list">
          {(
            [
              ["pdf", "PDF", issue.exact.pdf_bytes, issue.exact.pdf_hash],
              ["html", "HTML", issue.exact.html_bytes, issue.exact.html_hash],
              ["manifest", "Manifest", null, null],
            ] as const
          ).map(([type, label, bytes, hash]) => (
            <article key={type}>
              <ProductIcon name="documents" />
              <div>
                <strong>{label}</strong>
                <p>
                  {bytes === null
                    ? "Retained issue manifest"
                    : `${bytes.toLocaleString()} bytes`}
                </p>
                {hash && <code title={hash}>{hash}</code>}
              </div>
              <ButtonLink href={issue.files![type]}>
                {type === "html" ? "Open HTML" : `Download ${label}`}
              </ButtonLink>
            </article>
          ))}
        </div>
      ) : (
        <p className="output-note">
          File actions are unavailable. Refresh to recheck the same issue, or
          ask the service owner to investigate its retained storage.
        </p>
      )}
      <h2>Issue facts</h2>
      <dl className="output-facts">
        <dt>Issue identity</dt>
        <dd className="output-hash">{issue.id}</dd>
        <dt>Output hash</dt>
        <dd className="output-hash">{issue.output_hash}</dd>
        <dt>Prepared</dt>
        <dd>
          <OutputTime value={issue.exact.prepared_at} />
        </dd>
        <dt>Template</dt>
        <dd className="output-hash">
          {issue.exact.template.id} · v{issue.exact.template.version}
        </dd>
        <dt>Source hash</dt>
        <dd className="output-hash">{issue.exact.source_hash}</dd>
        <dt>Generated bytes</dt>
        <dd>
          {issue.exact.pdf_bytes.toLocaleString()} PDF ·{" "}
          {issue.exact.html_bytes.toLocaleString()} HTML
        </dd>
        <dt>Source applicability</dt>
        <dd>
          {issue.pack_applicable === null
            ? "No report approval inferred"
            : issue.pack_applicable
              ? "Applicable to current appointment"
              : "Not applicable to current appointment"}
        </dd>
      </dl>
      <p className="output-note">
        Preparation, issued identity, source applicability and distribution are
        separate facts. Opening or downloading is not acknowledgement or content
        acceptance.
      </p>
    </>
  );
}
function DistributionAttempt({
  attempt,
  onAction,
  eligible,
}: {
  attempt: Attempt;
  onAction: (intent: OutputIntent) => void;
  eligible: boolean;
}) {
  return (
    <article className="output-attempt">
      <header>
        <strong>Synthetic attempt</strong>
        <Status value={attempt.state} />
      </header>
      <dl className="output-facts">
        <dt>Attempt</dt>
        <dd className="output-hash">{attempt.id}</dd>
        <dt>Recovery owner</dt>
        <dd>{attempt.recovery_owner_name ?? "Not provided"}</dd>
        <dt>Version</dt>
        <dd>{attempt.version}</dd>
        <dt>External delivery</dt>
        <dd>Not recorded</dd>
      </dl>
      {attempt.events.map((e) => (
        <div key={e.id} className="output-event">
          <strong>
            {friendly(e.action)} · {friendly(e.state)}
          </strong>
          <p>
            <OutputTime value={e.occurred_at} /> ·{" "}
            {e.actor_name ?? "Actor not provided"}
          </p>
          <p>{e.reason}</p>
          <p>{e.evidence}</p>
        </div>
      ))}
      {["Prepared", "OutcomeUnknown"].includes(attempt.state) && (
        <Button
          disabled={!eligible}
          onClick={() =>
            onAction({
              action:
                attempt.state === "OutcomeUnknown"
                  ? "ReconcileDistribution"
                  : "RecordDistribution",
              fields: {
                attempt_id: attempt.id,
                expected_attempt_version: attempt.version,
              },
              label:
                attempt.state === "OutcomeUnknown"
                  ? "Reconcile outcome"
                  : "Record outcome",
              target: `Original attempt ${attempt.id} · version ${attempt.version}`,
            })
          }
        >
          {attempt.state === "OutcomeUnknown"
            ? "Reconcile original outcome"
            : "Record synthetic outcome"}
        </Button>
      )}
    </article>
  );
}
function OutputRecordLoaded({
  detail,
  context,
  actionError,
  actionLoading,
  onRefresh,
  saved,
  onSaved,
}: {
  detail: OutputDetail;
  context: OutputActionContext | null;
  actionError: unknown;
  actionLoading: boolean;
  onRefresh: () => void;
  saved: string;
  onSaved: (message: string) => void;
}) {
  const [tab, setTab] = useState("issue"),
    [intent, setIntent] = useState<OutputIntent | null>(null);
  const row = detail.output,
    issue = detail.selected_issue;
  const current =
    !!context &&
    context.version === row.version &&
    context.current_revision_id === row.current_revision_id &&
    context.current_issue_id === (row.current_issue?.id ?? null);
  const prepare = (recipient: string, label: string) => {
    if (!context || !issue || !canPrepare(detail, context, recipient)) return;
    setIntent({
      action: "PrepareDistribution",
      fields: {
        attempt_id: crypto.randomUUID(),
        issue_id: issue.id,
        recipient_id: recipient,
        expected_version: context.version,
      },
      label: "Prepare distribution",
      target: `${revisionLabel(issue.revision.revision)} · ${label} · exact issue ${issue.id}`,
    });
  };
  const availableRecipients = issue?.recipient_id
    ? [
        {
          id: issue.recipient_id,
          label: issue.recipient_name ?? "Frozen report recipient",
        },
      ]
    : (issue?.distribution.recipients.map((r) => ({
        id: r.id,
        label: r.display_name ?? "Permitted recipient",
      })) ?? []);
  const eligible = availableRecipients.filter(
    (r) => context && canPrepare(detail, context, r.id),
  );
  const withdraw = () => {
    if (current && context?.withdraw_pack)
      setIntent({
        action: "WithdrawPack",
        fields: { expected_version: context.version },
        label: "Withdraw pack",
        target: `Current issue ${context.current_issue_id} · source version ${context.version}`,
      });
  };
  const distribution = () => {
    if (eligible.length === 1) prepare(eligible[0].id, eligible[0].label);
    else setTab("distribution");
  };
  usePhoneHeader({
    title: row.reference,
    record: {
      more: [
        { label: "Refresh exact output", onSelect: onRefresh },
        { label: "Issue history", onSelect: () => setTab("history") },
        { label: "Distribution", onSelect: () => setTab("distribution") },
        ...(current && context?.withdraw_pack
          ? [{ label: "Withdraw pack", onSelect: withdraw }]
          : []),
      ],
    },
  });
  const more = (
    <WorklistMenu label="More output actions" icon="more" choices>
      <Link role="menuitem" href={row.native_href}>
        Open {familyLabel(row.kind).toLowerCase()}
      </Link>
      <button
        className="secondary"
        role="menuitem"
        data-menu-close
        onClick={onRefresh}
      >
        Refresh exact output
      </button>
      {row.kind === "JobPack" && (
        <button
          className="secondary"
          role="menuitem"
          data-menu-close
          disabled={!current || !context?.withdraw_pack}
          onClick={withdraw}
        >
          Withdraw pack
        </button>
      )}
      <Link role="menuitem" href="/documents/issues">
        All outputs
      </Link>
    </WorklistMenu>
  );
  return (
    <section
      id="ppo-outputs"
      className="output-record"
      data-module-layout="full-bleed"
      aria-label="Exact output record"
    >
      <RecordIdentity reference={row.reference} title="Outputs" />
      <header className="output-record-header">
        <div>
          <h1>
            {row.reference} <Status value={row.source_state} />
          </h1>
          <p>
            {familyLabel(row.kind)} ·{" "}
            {row.kind === "JobPack" ? "OUT-09" : "OUT-10"} ·{" "}
            {row.work_order.reference} · {row.appointment.reference}
          </p>
          <p>
            {row.labels.service_owner ?? "Owner not provided"} ·{" "}
            {row.labels.company ?? "Company not provided"}
          </p>
        </div>
        <div className="output-header-actions">
          <ButtonLink href={row.native_href}>
            Open {familyLabel(row.kind).toLowerCase()}
          </ButtonLink>
          <Button
            variant="primary"
            disabled={!current || !eligible.length}
            onClick={distribution}
          >
            Prepare distribution
          </Button>
          {more}
        </div>
      </header>
      <div className="output-record-facts">
        <span>
          Selected issue{" "}
          <strong>
            {issue ? revisionLabel(issue.revision.revision) : "None"}
          </strong>
        </span>
        <span>
          {issue?.is_current_issue
            ? "Current issue"
            : issue
              ? "Earlier issue"
              : "Not issued"}
        </span>
        <span>
          Current revision{" "}
          <strong>{revisionLabel(row.current_revision_number)}</strong>
        </span>
        <span>
          Exact output <strong>{friendly(detail.availability)}</strong>
        </span>
        {issue?.pack_applicable !== null && issue && (
          <span>
            Pack{" "}
            <strong>
              {issue.pack_applicable ? "applicable" : "not applicable"}
            </strong>
          </span>
        )}
      </div>
      <div className="output-record-body">
        <aside className="output-record-details">
          <h2>Output</h2>
          <OutputFacts row={row} />
          <p className="output-note">
            Current source facts can differ from the selected issue. Issued
            bytes and responses remain tied to their original identity.
          </p>
        </aside>
        <div className="output-record-main">
          <RecordTabs
            id="output-record"
            label="Output views"
            tabs={tabs.filter(
              (t) =>
                t.id !== "preparation" ||
                detail.preparation_visibility === "Internal",
            )}
            value={tab}
            onChange={setTab}
          />
          {saved && (
            <p className="output-note" role="status">
              {saved}
            </p>
          )}
          {!!context && !current && (
            <p className="output-warning" role="alert">
              Source facts changed between reads. Refresh before starting an
              action. Original command recovery remains available.
            </p>
          )}
          {actionLoading ? (
            <p className="output-note" role="status">
              Checking native action authority…
            </p>
          ) : actionError ? (
            <div className="output-note">
              {isDenied(actionError) ? (
                "Controlled actions and attempt recovery are not permitted for this source. Exact read access is separate."
              ) : (
                <>
                  <ReadState
                    loading={false}
                    error={actionError}
                    retry={onRefresh}
                  />
                  <p>
                    Action history is unavailable; no empty distribution history
                    is implied.
                  </p>
                </>
              )}
            </div>
          ) : null}
          <RecordPanel id="output-record" tab="issue" value={tab}>
            <ExactIssue detail={detail} />
            <details className="output-phone-details">
              <summary>Output and source details</summary>
              <OutputFacts row={row} />
            </details>
          </RecordPanel>
          <RecordPanel id="output-record" tab="history" value={tab}>
            <h2>Issue history</h2>
            <p>
              {detail.history_coverage === "SelectedIssueOnly"
                ? "Only your permitted selected issue is provided."
                : "Every retained issue for this output is listed. Selecting an earlier issue keeps its exact bytes and responses."}
            </p>
            {detail.issue_history.map((item) => (
              <article className="output-history-row" key={item.id}>
                <div>
                  <strong>{revisionLabel(item.revision_number)}</strong>{" "}
                  <Status
                    value={
                      item.id === row.current_issue?.id
                        ? "Current issue"
                        : "Earlier issue"
                    }
                  />
                  <p>
                    <OutputTime value={item.issued_at} />
                  </p>
                  <code className="output-hash">{item.output_hash}</code>
                </div>
                <ButtonLink
                  href={outputHref(row.kind, row.id, item.id)}
                  aria-current={item.id === issue?.id ? "page" : undefined}
                >
                  {item.id === issue?.id
                    ? "Viewing this issue"
                    : "View this issue"}
                </ButtonLink>
              </article>
            ))}
            {!detail.issue_history.length && (
              <p>No issued identity is provided.</p>
            )}
            <h2>Selected issue events</h2>
            {issue?.events.length ? (
              issue.events.map((event) => (
                <article className="output-event" key={event.id}>
                  <strong>{friendly(event.kind)}</strong>
                  <p>
                    <OutputTime value={event.occurred_at} /> ·{" "}
                    {event.actor_name ?? "Actor not provided"}
                  </p>
                  {event.reason && <p>{event.reason}</p>}
                </article>
              ))
            ) : (
              <p>No source issue events recorded for this selected issue.</p>
            )}
          </RecordPanel>
          <RecordPanel id="output-record" tab="distribution" value={tab}>
            <h2>Distribution</h2>
            <p className="output-note">
              Synthetic distribution only. External sent and delivered times are
              not recorded. An opened or downloaded event does not establish a
              recipient response.
            </p>
            {!issue ? (
              <p>No issued output is provided.</p>
            ) : (
              <>
                {row.kind === "JobPack" ? (
                  <>
                    <p>
                      {issue.is_current_issue
                        ? progressLabel(row.recipient_summary)
                        : "Recipient progress below belongs only to this selected issue."}
                    </p>
                    {issue.distribution.recipients.map((recipient) => {
                      const ack = acknowledged(recipient, issue.output_hash);
                      return (
                        <article
                          className="output-recipient"
                          key={recipient.id}
                        >
                          <header>
                            <div>
                              <h3>
                                {recipient.display_name ??
                                  "Permitted recipient"}
                              </h3>
                              <p>
                                {recipient.required ? "Required" : "Optional"} ·
                                Assignment v{recipient.assignment_version}
                              </p>
                            </div>
                            <Status
                              value={ack ? "Acknowledged" : "Not acknowledged"}
                            />
                          </header>
                          <dl className="output-facts">
                            <dt>Sent externally</dt>
                            <dd>Not recorded</dd>
                            <dt>Delivered</dt>
                            <dd>Not recorded</dd>
                            <dt>Opened</dt>
                            <dd>
                              {recipient.events.filter(
                                (e) => e.kind === "Opened",
                              ).length
                                ? recipient.events
                                    .filter((e) => e.kind === "Opened")
                                    .map((e) => (
                                      <div key={e.id}>
                                        <OutputTime value={e.occurred_at} />
                                      </div>
                                    ))
                                : "Not recorded"}
                            </dd>
                            <dt>Downloaded</dt>
                            <dd>
                              {recipient.events.filter(
                                (e) => e.kind === "Downloaded",
                              ).length
                                ? recipient.events
                                    .filter((e) => e.kind === "Downloaded")
                                    .map((e) => (
                                      <div key={e.id}>
                                        <OutputTime value={e.occurred_at} />
                                      </div>
                                    ))
                                : "Not recorded"}
                            </dd>
                            <dt>Acknowledged</dt>
                            <dd>
                              {ack ? (
                                <OutputTime value={ack.acknowledged_at} />
                              ) : (
                                "Not recorded for this exact hash and recipient"
                              )}
                            </dd>
                          </dl>
                          {recipient.events
                            .filter((e) => e.kind === "SimulatedSent")
                            .map((e) => (
                              <p key={e.id}>
                                Native simulated send ·{" "}
                                <OutputTime value={e.occurred_at} />
                              </p>
                            ))}
                          <Button
                            disabled={
                              !current ||
                              !context ||
                              !canPrepare(detail, context, recipient.id)
                            }
                            onClick={() =>
                              prepare(
                                recipient.id,
                                recipient.display_name ?? "Permitted recipient",
                              )
                            }
                          >
                            Prepare distribution
                          </Button>
                          {context?.distribution_attempts
                            .filter(
                              (a) =>
                                a.issue_id === issue.id &&
                                a.recipient_id === recipient.id,
                            )
                            .map((a) => (
                              <DistributionAttempt
                                key={a.id}
                                attempt={a}
                                onAction={setIntent}
                                eligible={current}
                              />
                            ))}
                        </article>
                      );
                    })}
                    {!issue.distribution.recipients.length && (
                      <p>No permitted recipient rows are provided.</p>
                    )}
                  </>
                ) : (
                  <>
                    <article className="output-recipient">
                      <h3>
                        {issue.recipient_name ?? "Frozen report recipient"}
                      </h3>
                      <p>
                        Recipient identity frozen on this issued report. Current
                        permitted name shown where available.
                      </p>
                      <dl className="output-facts">
                        <dt>Recipient</dt>
                        <dd className="output-hash">{issue.recipient_id}</dd>
                        <dt>External delivery</dt>
                        <dd>Not recorded</dd>
                        <dt>Opened / downloaded</dt>
                        <dd>Not recorded by this source</dd>
                      </dl>
                      <Button
                        disabled={
                          !current ||
                          !context ||
                          !issue.recipient_id ||
                          !canPrepare(detail, context, issue.recipient_id)
                        }
                        onClick={() =>
                          issue.recipient_id &&
                          prepare(
                            issue.recipient_id,
                            issue.recipient_name ?? "Frozen report recipient",
                          )
                        }
                      >
                        Prepare distribution
                      </Button>
                      {context?.distribution_attempts
                        .filter((a) => a.issue_id === issue.id)
                        .map((a) => (
                          <DistributionAttempt
                            key={a.id}
                            attempt={a}
                            onAction={setIntent}
                            eligible={current}
                          />
                        ))}
                    </article>
                    <h2>Report-content responses</h2>
                    <p>
                      Attendance acknowledgement belongs to the attendance
                      record. It is not acceptance of this report’s contents.
                    </p>
                    {issue.distribution.responses.map((response) => (
                      <article className="output-event" key={response.id}>
                        <strong>
                          {friendly(response.response)}
                          {response.superseded ? " · Superseded" : ""}
                        </strong>
                        <p>
                          {response.respondent_name} ·{" "}
                          {response.respondent_role}
                        </p>
                        <p>
                          Presented <OutputTime value={response.presented_at} />{" "}
                          · Received <OutputTime value={response.received_at} />
                        </p>
                        {response.restrictions && (
                          <p>Restrictions: {response.restrictions}</p>
                        )}
                        {response.correction_reason && (
                          <p>Correction: {response.correction_reason}</p>
                        )}
                        <code className="output-hash">
                          {response.presented_hash}
                        </code>
                      </article>
                    ))}
                    {!issue.distribution.responses.length && (
                      <p>
                        No report-content response is recorded for this exact
                        issue.
                      </p>
                    )}
                  </>
                )}
                {context &&
                  !context.distribution_attempts.some(
                    (a) => a.issue_id === issue.id,
                  ) && (
                    <p>
                      No controlled synthetic attempts are recorded for this
                      selected issue. Native events, if present, remain
                      separate.
                    </p>
                  )}
              </>
            )}
          </RecordPanel>
          <RecordPanel id="output-record" tab="preparation" value={tab}>
            <h2>Preparation</h2>
            <p>
              Source preparation and review happen on the native page. These are
              original issue jobs, their generated output records and resulting
              issued identities.
            </p>
            <div className="output-actions">
              <ButtonLink href={row.native_href}>
                Open {familyLabel(row.kind).toLowerCase()}
              </ButtonLink>
              {context && (
                <Button
                  variant="primary"
                  disabled={!current || !context.request_issue.available}
                  onClick={() =>
                    setIntent({
                      action: "RequestIssue",
                      fields: context.request_issue.basis,
                      label: "Request issue",
                      target: `Current revision ${revisionLabel(row.current_revision_number)} · source version ${context.version}`,
                    })
                  }
                >
                  Request issue
                </Button>
              )}
            </div>
            {context && <p>{context.request_issue.reason}</p>}
            {detail.preparations.map((job) => {
              const recovery = context?.jobs.find((j) => j.id === job.id);
              return (
                <article className="output-preparation" key={job.id}>
                  <header>
                    <strong>{revisionLabel(job.revision_number)}</strong>
                    <Status value={job.state} />
                  </header>
                  <dl className="output-facts">
                    <dt>Job</dt>
                    <dd className="output-hash">{job.id}</dd>
                    <dt>Requested</dt>
                    <dd>
                      <OutputTime value={job.requested_at} />
                    </dd>
                    <dt>Attempts</dt>
                    <dd>{job.attempts}</dd>
                    <dt>Generated output</dt>
                    <dd>
                      {job.has_recorded_output ? (
                        <>
                          Recorded · <OutputTime value={job.prepared_at} />
                        </>
                      ) : (
                        "Not recorded"
                      )}
                    </dd>
                    <dt>Issued identity</dt>
                    <dd>
                      {job.issue_id ? (
                        <Link href={outputHref(row.kind, row.id, job.issue_id)}>
                          Open exact issue
                        </Link>
                      ) : (
                        "Not issued"
                      )}
                    </dd>
                    <dt>Recovery owner</dt>
                    <dd>{recovery?.recovery_owner_name ?? "Not provided"}</dd>
                    <dt>Failure</dt>
                    <dd>{job.error_code ?? "Not recorded"}</dd>
                  </dl>
                  {recovery && (
                    <Button
                      disabled={!current || !recovery.recoverable}
                      onClick={() =>
                        setIntent({
                          action: "RecoverIssue",
                          fields: { job_id: job.id },
                          label: "Recover preparation",
                          target: `Original job ${job.id}`,
                        })
                      }
                    >
                      Recover original preparation
                    </Button>
                  )}
                  {job.state === "StaleSource" && (
                    <p>
                      Source changed. Review it on the native page before a
                      deliberate new revision; do not replace this job’s output.
                    </p>
                  )}
                  {job.state === "Running" && !recovery?.recoverable && (
                    <p>
                      The original worker may still hold a lease. Refresh after
                      it finishes; do not create another job.
                    </p>
                  )}
                </article>
              );
            })}
            {!detail.preparations.length && (
              <p>No preparation jobs are recorded.</p>
            )}
          </RecordPanel>
          <p className="output-as-at">
            As at <OutputTime value={detail.as_at} /> · Brisbane{" "}
            <Button variant="quiet" onClick={onRefresh}>
              Refresh
            </Button>
          </p>
        </div>
      </div>
      <footer className="output-phone-actions">
        {more}
        {current && eligible.length ? (
          <Button variant="primary" onClick={distribution}>
            Prepare distribution
          </Button>
        ) : (
          <ButtonLink href={row.native_href}>
            Open {familyLabel(row.kind).toLowerCase()}
          </ButtonLink>
        )}
      </footer>
      {context && (
        <OutputCommand
          key={`${context.workspace_id}:${context.actor_id}:${row.id}`}
          detail={detail}
          context={context}
          intent={intent}
          onIntent={setIntent}
          onSaved={(message) => {
            onSaved(message);
            onRefresh();
          }}
        />
      )}
    </section>
  );
}
export function OutputRecordScreen({
  kind,
  id,
}: {
  kind: OutputKind;
  id: string;
}) {
  const params = useSearchParams(),
    selected = params.get("issue");
  const [saved, setSaved] = useState("");
  const detail = useResource<OutputDetail>(
      `document-outputs/${id}?kind=${kind}${selected ? `&issue_id=${encodeURIComponent(selected)}` : ""}`,
    ),
    actions = useResource<OutputActionContext>(
      `document-outputs/${id}/actions?kind=${kind}`,
    );
  const refresh = () => {
    detail.reload();
    actions.reload();
  };
  if (detail.loading || detail.error || !detail.data)
    return (
      <section id="ppo-outputs" className="output-read-state">
        <h1>Outputs</h1>
        {saved && <p role="status">{saved}</p>}
        <ReadState
          loading={detail.loading}
          error={detail.error}
          retry={refresh}
        />
        <p>
          Exact issue details are unavailable until this read succeeds. No
          successor output is substituted.
        </p>
        <ButtonLink href="/documents/issues">All outputs</ButtonLink>
      </section>
    );
  return (
    <OutputRecordLoaded
      key={`${kind}:${id}:${selected ?? "current"}`}
      detail={detail.data}
      context={!actions.loading && !actions.error ? actions.data : null}
      actionError={actions.error}
      actionLoading={actions.loading}
      onRefresh={refresh}
      saved={saved}
      onSaved={setSaved}
    />
  );
}
