        (['docs/standards/document-register.csv', 'docs/delivery/plan.md'], True),
        (['docs/blueprints/BP-01-master-blueprint.md', 'README.md', 'AGENTS.md', 'CONTRIBUTING.md'], True),
        (['db/reservations/0110.md'], True),
