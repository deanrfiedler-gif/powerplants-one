#!/usr/bin/env python3
"""Validate documentation sources; render disposable combined views under tmp/.

The tracked landing pages contain navigation, a fixed insertion marker and the
legacy record. Feature PRs change fragments only. --check validates the sources
without writing. The default command renders local links; --web-ref COMMIT
renders source-bound GitHub links for a downloadable CI artifact. No command
writes generated prose into a tracked landing page.
"""
from pathlib import Path
import argparse
import datetime
import os
import re
import subprocess
import sys
from urllib.parse import quote, unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
FRAGMENTS = ROOT / 'docs/status'
LEGACY_INDEX = FRAGMENTS / 'legacy-index.txt'
START = '<!-- fragments:start -->'
END = '<!-- fragments:end -->'
DECISION_MARK = '<!-- decision-index -->'
MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August',
          'September', 'October', 'November', 'December']
NOTICE = ('<!-- Generated by scripts/build_status.py from docs/status/. Do not edit between the fragment '
          'markers: add a fragment instead. Entries below the end marker are the frozen legacy record. -->')
PLACEHOLDER = '\n<!-- Combined views are generated under tmp/documentation/; commit sources only. -->\n'
OUTPUT = ROOT / 'tmp/documentation'
REPOSITORY = 'https://github.com/deanrfiedler-gif/powerplants-one'
FILENAME = re.compile(r'^(\d{4}-\d{2}-\d{2})-[a-z0-9][a-z0-9-]*\.md$')
LINK = re.compile(r'(\]\()([^)\s]+)(\))')

TARGETS = {
    'STATUS': ROOT / 'docs/STATUS.md',
    'DECISIONS': ROOT / 'docs/decisions/README.md',
}
PROBLEMS = []


def problem(message):
    PROBLEMS.append(message)


def read(path):
    return path.read_text(encoding='utf-8').replace('\r\n', '\n')


def write(path, text):
    with path.open('w', encoding='utf-8', newline='\n') as handle:
        handle.write(text)


def long_date(value):
    return f'{value.day} {MONTHS[value.month - 1]} {value.year}'


def rebase_links(text, source_dir, target_dir, web_ref=None):
    """Rewrite relative inline links so a fragment reads correctly where it is rendered."""
    def swap(match):
        target = match.group(2)
        parts = urlsplit(target)
        if parts.scheme or parts.netloc or target.startswith('#') or not parts.path:
            return match.group(0)
        resolved = (source_dir / unquote(parts.path)).resolve()
        if not resolved.is_relative_to(ROOT):
            problem(f'local link escapes repository: {target}')
            return match.group(0)
        if not resolved.exists():
            problem(f'broken local link: {target}')
            return match.group(0)
        if web_ref:
            kind = 'tree' if resolved.is_dir() else 'blob'
            relative = f'{REPOSITORY}/{kind}/{web_ref}/{quote(resolved.relative_to(ROOT).as_posix())}'
        else:
            relative = quote(os.path.relpath(resolved, target_dir).replace(os.sep, '/'), safe='/')
        relative += f'?{parts.query}' if parts.query else ''
        suffix = f'#{parts.fragment}' if parts.fragment else ''
        return f'{match.group(1)}{relative}{suffix}{match.group(3)}'
    return LINK.sub(swap, text)


def load_fragments():
    """Return fragments newest first: dict(title, date, status, decision, name)."""
    result = []
    for path in sorted(FRAGMENTS.glob('*.md')):
        if path.name == 'README.md':
            continue
        name = path.name
        match = FILENAME.match(name)
        if not match:
            problem(f'docs/status/{name}: name must be YYYY-MM-DD-slug.md (lowercase letters, digits, hyphens)')
            continue
        text = read(path)
        head = re.match(r'^---\n(.*?)\n---\n(.*)$', text, re.S)
        if not head:
            problem(f'docs/status/{name}: missing front matter (---, title:, date:, ---)')
            continue
        meta = {}
        for line in head.group(1).splitlines():
            key, sep, value = line.partition(':')
            if sep:
                meta[key.strip()] = value.strip()
        title = meta.get('title', '')
        try:
            date = datetime.date.fromisoformat(meta.get('date', ''))
        except ValueError:
            problem(f'docs/status/{name}: date must be an ISO date such as 2026-10-18')
            continue
        if not title:
            problem(f'docs/status/{name}: title is required')
            continue
        if date.isoformat() != match.group(1):
            problem(f'docs/status/{name}: filename date {match.group(1)} differs from front matter date {date.isoformat()}')
        body = head.group(2).strip('\n')
        status, _, decision = body.partition(DECISION_MARK)
        status, decision = status.strip('\n'), decision.strip('\n')
        if not status.strip():
            problem(f'docs/status/{name}: status body is empty')
            continue
        if re.search(r'^#{1,2} ', status, re.M):
            problem(f'docs/status/{name}: the status body must not contain # or ## headings; the title comes from front matter')
        result.append({'name': name, 'title': title, 'date': date, 'status': status, 'decision': decision})
    result.sort(key=lambda f: (f['date'], f['name']), reverse=True)
    return result


def render_status(fragments):
    blocks = []
    for f in fragments:
        body = rebase_links(f['status'], FRAGMENTS, TARGETS['STATUS'].parent)
        blocks.append(f"## {f['title']} — {long_date(f['date'])}\n\n{body}\n")
    return '\n'.join(blocks) + ('\n' if blocks else '')


def render_decisions(fragments):
    blocks = []
    for f in fragments:
        if f['decision'].strip():
            blocks.append(rebase_links(f['decision'], FRAGMENTS, TARGETS['DECISIONS'].parent) + '\n')
    return '\n'.join(blocks) + ('\n' if blocks else '')


def split(text, label):
    """Return (head, generated, legacy) around the markers, or None if absent."""
    if text.count(START) != 1 or text.count(END) != 1 or text.index(START) > text.index(END):
        problem(f'{label}: needs exactly one {START} followed by one {END}')
        return None
    head, rest = text.split(START, 1)
    generated, legacy = rest.split(END, 1)
    return head, generated, legacy


def assemble(head, rendered, legacy):
    return f'{head}{START}\n{NOTICE}\n\n{rendered}{END}{legacy}'


def legacy_items(label, legacy):
    """Headings (STATUS) or leading paragraph lines (DECISIONS) of the frozen part."""
    items, fenced, fresh = [], False, True
    for line in legacy.splitlines():
        if re.match(r'^\s*(`{3,}|~{3,})', line):
            fenced = not fenced
        if fenced:
            continue
        if label == 'STATUS':
            if line.startswith('## '):
                items.append(line.strip())
        else:
            if line.strip() and fresh and not line.startswith(('-', '*', '#', ' ', '|', '<!--')):
                items.append(line.strip()[:80])
            fresh = not line.strip()
    return items


def load_accepted():
    accepted = {'STATUS': [], 'DECISIONS': []}
    if not LEGACY_INDEX.exists():
        return accepted
    for line in read(LEGACY_INDEX).splitlines():
        label, sep, item = line.partition('\t')
        if sep and label in accepted:
            accepted[label].append(item)
    return accepted


def build(web_ref=None):
    fragments = load_fragments()
    rendered = {'STATUS': render_status(fragments), 'DECISIONS': render_decisions(fragments)}
    legacy_found = {}
    outputs = {}
    for label, path in TARGETS.items():
        text = read(path)
        parts = split(text, path.relative_to(ROOT).as_posix())
        if not parts:
            continue
        head, generated, legacy = parts
        legacy_found[label] = legacy_items(label, legacy)
        if generated != PLACEHOLDER:
            problem(f'{path.relative_to(ROOT).as_posix()}: tracked landing pages must contain only the fixed insertion marker. '
                    'Keep your docs/status/ fragment and restore this page from current main; generated views belong in tmp/documentation/')
        expected = assemble(head, rendered[label], legacy)
        output_name = 'STATUS.md' if label == 'STATUS' else 'decisions.md'
        source_note = f'\nSource: [{web_ref}]({REPOSITORY}/commit/{web_ref}).\n' if web_ref else '\nLocal view of the current working tree; not a publication or approval.\n'
        outputs[output_name] = source_note + rebase_links(expected, path.parent, OUTPUT, web_ref)
    return fragments, legacy_found, outputs


def check_legacy(legacy_found):
    accepted = load_accepted()
    for label, found in legacy_found.items():
        if sorted(found) != sorted(accepted[label]):
            added = sorted(set(found) - set(accepted[label]))
            removed = sorted(set(accepted[label]) - set(found))
            where = TARGETS[label].relative_to(ROOT).as_posix()
            detail = '; '.join(filter(None, [f'added {added[:3]}' if added else '', f'removed {removed[:3]}' if removed else '']))
            problem(f'{where}: the frozen legacy entries changed ({detail}). New entries go in a docs/status/ fragment. '
                    'If a reviewed edit to legacy text really changes an entry, run python3 scripts/build_status.py --accept-legacy')


def accept_legacy(legacy_found):
    lines = [f'{label}\t{item}' for label in ('STATUS', 'DECISIONS') for item in legacy_found.get(label, [])]
    write(LEGACY_INDEX, '\n'.join(lines) + '\n')


def new_fragment(title, with_decision):
    today = datetime.date.today()
    slug = re.sub(r'[^a-z0-9]+', '-', title.lower()).strip('-')[:60]
    path = FRAGMENTS / f'{today.isoformat()}-{slug}.md'
    if path.exists():
        sys.exit(f'{path.relative_to(ROOT)} already exists')
    extra = f'\n\n{DECISION_MARK}\n[Record title](../decisions/record.md) (ID) one or two sentences for the decisions index.' if with_decision else ''
    write(path, f'---\ntitle: {title}\ndate: {today.isoformat()}\n---\n\nWhat is now true, what was checked, what is not done or not verified. Links are relative to this file.{extra}\n')
    print(path.relative_to(ROOT).as_posix())


def check_status():
    """Entry point for scripts/check_foundation.py. Returns a list of problem strings."""
    PROBLEMS.clear()
    _, legacy_found, _ = build()
    if len(legacy_found) == len(TARGETS):
        check_legacy(legacy_found)
    return list(PROBLEMS)


def verify_web_ref(ref):
    """Published links must describe this exact clean checkout, not an arbitrary SHA."""
    for args, expected in [(['rev-parse', 'HEAD'], ref),
                           (['status', '--porcelain', '--untracked-files=normal'], '')]:
        result = subprocess.run(['git', *args], cwd=ROOT, capture_output=True, text=True, encoding='utf-8')
        if result.returncode:
            raise ValueError(result.stderr.strip() or 'cannot verify artifact source')
        if result.stdout.strip() != expected:
            raise ValueError('--web-ref must equal HEAD in a clean checkout; commit changes or render a local view without --web-ref')


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--new', metavar='TITLE')
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--accept-legacy', action='store_true')
    parser.add_argument('--decision', action='store_true', help='include a decision-index section with --new')
    parser.add_argument('--web-ref', help='full commit SHA for source-bound artifact links')
    args = parser.parse_args(argv)
    if args.decision and not args.new:
        parser.error('--decision requires --new')
    if args.web_ref and (not re.fullmatch(r'[0-9a-f]{40}', args.web_ref) or args.new or args.check or args.accept_legacy):
        parser.error('--web-ref requires a full lowercase commit SHA and render mode')
    if args.web_ref:
        try:
            verify_web_ref(args.web_ref)
        except (OSError, ValueError) as exc:
            parser.error(str(exc))
    if args.new:
        new_fragment(args.new, args.decision)
        return 0
    PROBLEMS.clear()
    fragments, legacy_found, outputs = build(args.web_ref)
    if args.accept_legacy:
        if PROBLEMS or len(legacy_found) != len(TARGETS):
            for message in PROBLEMS:
                print(message, file=sys.stderr)
            return 1
        accept_legacy(legacy_found)
        print(f'recorded {sum(len(v) for v in legacy_found.values())} legacy entries in {LEGACY_INDEX.relative_to(ROOT).as_posix()}')
        return 0
    if len(legacy_found) == len(TARGETS):
        check_legacy(legacy_found)
    for message in PROBLEMS:
        print(message, file=sys.stderr)
    if PROBLEMS:
        return 1
    if args.check:
        print(f'status sources: passed ({len(fragments)} fragments; no tracked output required)')
        return 0
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for name, content in outputs.items():
        write(OUTPUT / name, content)
    print(f'rendered {len(fragments)} fragment(s) into {OUTPUT.relative_to(ROOT).as_posix()}/ (ignored; do not commit)')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
